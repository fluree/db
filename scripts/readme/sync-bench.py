#!/usr/bin/env python3
"""Regenerate the README benchmark block and charts from a fluree/benchmark-db checkout.

The block between <!-- BENCH:START --> and <!-- BENCH:END --> in README.md is
generated by this script; do not edit it by hand. Every number is computed from
benchmark-db's raw results, using the same rules as benchmark-db's own
common/make_charts.py, not copied from its prose:

  DBLP-core        sparqloscope/reports/dblp-core/engines/<engine>_summary.tsv
                   penalized geometric mean (SPARQLoscope P=2): a query passes when its
                   status is 200; any other status counts as 2 x the timeout.
  Wikidata-truthy  sparqloscope/reports/wikidata-truthy/engines/<engine>_summary.tsv
                   same rule, with that report's timeout.
  WGPB             wgpb/reports/wikidata-all/meta.json (results block).
  Pokec            benchgraph/reports/pokec/summary.tsv
                   geometric mean of per-query medians at the large scale, reads and
                   writes separately.

Versions and dates come from each report's meta.json.

It also draws two README-only charts of the DBLP-core results, in Fluree brand
colors on a linear scale: docs/assets/readme/dblp-core-geomean-{light,dark}.svg.
The axis ends at CAP_MS; slower engines are drawn clipped and labeled off scale.

Usage:
  python3 scripts/readme/sync-bench.py --bench-repo ../benchmark-db [--check]

--check exits 1 if README.md or a chart would change (for CI).
Standard library only.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
README = ROOT / "README.md"
ASSETS = ROOT / "docs/assets/readme"

START = "<!-- BENCH:START -->"
END = "<!-- BENCH:END -->"

B = "benchmarks"
DBLP = f"{B}/sparqloscope/reports/dblp-core"
TRUTHY = f"{B}/sparqloscope/reports/wikidata-truthy"
WGPB = f"{B}/wgpb/reports/wikidata-all"
POKEC = f"{B}/benchgraph/reports/pokec"
POKEC_PEERS = ["falkordb", "memgraph", "neo4j"]
PENALTY = 2
CAP_MS = 500  # README chart axis end; slower engines are drawn clipped

# Brand tokens (docs/assets/readme/BRAND.md).
VIBRANT = "#13C6FF"
THEMES = {
    "light": {"ink": "#091133", "muted": "#556480", "grid": "#E3E8F0", "other": "#A3AEC2", "inside": "#091133", "hatch": "#C9D3EC"},
    "dark": {"ink": "#F6F6F6", "muted": "#9AA6BD", "grid": "#2A3350", "other": "#4D5A78", "inside": "#F6F6F6", "hatch": "#3A4664"},
}


def geomean(values: list[float]) -> float:
    return math.exp(sum(math.log(v) for v in values) / len(values))


def sparqloscope(bench: pathlib.Path, report: str, engine: str, timeout_ms: float):
    """Return (penalized geomean ms, passed, total), using benchmark-db's make_charts.py rule."""
    path = bench / report / "engines" / f"{engine}_summary.tsv"
    with path.open(newline="") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    values = [float(r["median_ms"]) if r["status"] == "200" else PENALTY * timeout_ms for r in rows]
    passed = sum(r["status"] == "200" for r in rows)
    return geomean(values), passed, len(rows)


def pokec_geomeans(bench: pathlib.Path) -> dict[str, dict[str, float]]:
    path = bench / POKEC / "summary.tsv"
    with path.open(newline="") as fh:
        rows = [r for r in csv.DictReader(fh, delimiter="\t") if r["scale"] == "large"]
    out: dict[str, dict[str, float]] = {}
    for kind in ("read", "write"):
        subset = [r for r in rows if r["kind"] == kind]
        out[kind] = {e: geomean([float(r[f"{e}_ms"]) for r in subset]) for e in ["fluree", *POKEC_PEERS]}
        out[kind]["_n"] = len(subset)
    return out


def fmt_ms(ms: float) -> str:
    if ms >= 1000:
        return f"{ms / 1000:,.1f} s"
    if ms >= 10:
        return f"{ms:,.1f} ms"
    return f"{ms:.2f} ms"


def fmt_ratio(r: float) -> str:
    return f"{r:.1f}×" if r < 100 else f"{r:,.0f}×"


def bench_commit(bench: pathlib.Path) -> str:
    try:
        return subprocess.check_output(["git", "-C", str(bench), "rev-parse", "--short", "HEAD"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def dblp_chart(rows: list[tuple[str, float, int, int]], subtitle: str, theme: str) -> str:
    """Horizontal linear-scale bars, Fluree in brand blue. rows: (label, ms, passed, total), Fluree first.

    Bars are exactly proportional to time up to CAP_MS. Slower engines are drawn as
    hatched "off scale" bars clipped at the axis end, with their real value printed.
    """
    c = THEMES[theme]
    W, L, R, T, row_h, bh = 760, 120, 20, 72, 34, 22
    H = T + len(rows) * row_h + 44
    pw = W - L - R
    cap = CAP_MS

    def x(ms: float) -> float:
        return L + min(ms, cap) / cap * pw

    font = "font-family='-apple-system,BlinkMacSystemFont,Segoe UI,Helvetica,Arial,sans-serif'"
    s = [f"<svg xmlns='http://www.w3.org/2000/svg' width='{W}' height='{H}' viewBox='0 0 {W} {H}' {font}>"]
    s.append(f"<defs><pattern id='off-{theme}' width='7' height='7' patternTransform='rotate(45)' "
             f"patternUnits='userSpaceOnUse'><rect width='7' height='7' fill='{c['other']}'/>"
             f"<line x1='0' y1='0' x2='0' y2='7' stroke='{c['hatch']}' stroke-width='2.5'/></pattern></defs>")
    s.append(f"<text x='{L}' y='26' font-size='17' font-weight='700' fill='{c['ink']}'>"
             "DBLP-core · geometric-mean query time</text>")
    s.append(f"<text x='{L}' y='47' font-size='12.5' fill='{c['muted']}'>{esc(subtitle)}</text>")
    steps = 5
    for k in range(steps + 1):
        ms = cap * k / steps
        gx = x(ms)
        label = f"{ms / 1000:g} s" if ms >= 1000 else f"{ms:g} ms"
        s.append(f"<line x1='{gx:.1f}' y1='{T - 8}' x2='{gx:.1f}' y2='{H - 38}' stroke='{c['grid']}'/>")
        s.append(f"<text x='{gx:.1f}' y='{H - 22}' font-size='11' fill='{c['muted']}' "
                 f"text-anchor='middle'>{label}</text>")
    best = rows[0][1]
    for i, (label, ms, passed, total) in enumerate(rows):
        y = T + i * row_h
        is_f = i == 0
        clipped = ms > cap
        weight = "700" if is_f else "400"
        bx = x(ms)
        fill = VIBRANT if is_f else (f"url(#off-{theme})" if clipped else c["other"])
        s.append(f"<text x='{L - 12}' y='{y + 16}' font-size='13' font-weight='{weight}' "
                 f"fill='{c['ink']}' text-anchor='end'>{esc(label)}</text>")
        s.append(f"<rect x='{L}' y='{y}' width='{max(bx - L, 3):.1f}' height='{bh}' rx='3' fill='{fill}'/>")
        value = fmt_ms(ms)
        meta = f"  {'fastest' if is_f else fmt_ratio(ms / best) + ' slower'} · {passed}/{total} passed"
        if clipped:
            text = f"{value}{meta}  ▶ off scale"
            tw = len(text) * 6.5 + 14
            s.append(f"<rect x='{bx - tw:.1f}' y='{y}' width='{tw:.1f}' height='{bh}' rx='3' fill='{c['other']}'/>")
            s.append(f"<text x='{bx - 8:.1f}' y='{y + 16}' font-size='12.5' fill='{c['inside']}' "
                     f"text-anchor='end'>{esc(text)}</text>")
        else:
            s.append(f"<text x='{max(bx, L + 3) + 8:.1f}' y='{y + 16}' font-size='12.5' font-weight='{weight}' "
                     f"fill='{c['ink']}'>{esc(value)}<tspan font-weight='400' fill='{c['muted']}'>"
                     f"{esc(meta)}</tspan></text>")
    s.append(f"<text x='{L + pw / 2:.1f}' y='{H - 4}' font-size='12' font-weight='700' fill='{c['muted']}' "
             f"text-anchor='middle'>Lower is faster · bars to scale up to {cap:g} ms</text>")
    s.append("</svg>")
    return "\n".join(s) + "\n"


def render(bench: pathlib.Path) -> tuple[str, dict[str, str]]:
    dmeta = json.loads((bench / DBLP / "meta.json").read_text())
    tmeta = json.loads((bench / TRUTHY / "meta.json").read_text())
    wmeta = json.loads((bench / WGPB / "meta.json").read_text())
    pmeta = json.loads((bench / POKEC / "meta.json").read_text())

    # DBLP-core: every engine in the report, fastest first.
    d_timeout = dmeta["methodology"]["timeout_s"] * 1000
    d_rows = []
    for key, info in dmeta["engines"].items():
        ms, passed, total = sparqloscope(bench, DBLP, key, d_timeout)
        d_rows.append((info["label"], ms, passed, total, key))
    d_rows.sort(key=lambda r: r[1])
    d = {r[4]: r for r in d_rows}
    if d_rows[0][4] != "fluree":
        raise SystemExit("error: Fluree is no longer fastest on DBLP-core; review the README copy by hand")
    f_ms, f_pass, f_total = d["fluree"][1:4]
    q_ratio, v_ratio = d["qlever"][1] / f_ms, d["virtuoso"][1] / f_ms
    triples_m = round(dmeta["dataset"]["triples"] / 1e6)
    d_version = dmeta["engines"]["fluree"]["version"]
    d_date = dmeta["engines"]["fluree"].get("measured_at", "unknown date")
    d_hw = dmeta["hardware"]["instance"].replace("AWS ", "")

    # Wikidata-truthy and WGPB.
    t_timeout = tmeta["methodology"]["timeout_s"] * 1000
    t_f = sparqloscope(bench, TRUTHY, "fluree", t_timeout)
    t_q = sparqloscope(bench, TRUTHY, "qlever", t_timeout)
    t_version = tmeta["engines"]["fluree"]["version"]
    t_triples_b = tmeta["dataset"]["triples"] / 1e9
    w_res = wmeta["results"]
    w_triples_b = wmeta["dataset"]["triples"] / 1e9
    w_match = re.search(r"Fluree (v[\d.]+)", wmeta.get("status", ""))
    w_version = w_match.group(1) if w_match else "(version not recorded)"
    w_total = w_res["completed"] + w_res.get("timeouts", 0) + w_res.get("errors", 0)

    # Pokec.
    p = pokec_geomeans(bench)
    reads, writes = p["read"], p["write"]
    r_ratios = sorted(reads[e] / reads["fluree"] for e in POKEC_PEERS)
    w_ratios = sorted(writes[e] / writes["fluree"] for e in POKEC_PEERS)
    large = pmeta["dataset"]["scales"]["large"]
    p_version = pmeta["engines"]["fluree"]["version"]
    measured = pmeta["methodology"].get("measured", {})
    p_date = measured.get("fluree", "unknown date")
    p_peer_date = measured.get("neo4j", "an earlier date")
    p_hw = pmeta["hardware"]["instance"].replace("AWS ", "")
    n_queries = reads["_n"] + writes["_n"]

    if (d_version, d_date) == (p_version, p_date):
        fluree_line = f"Fluree {d_version}, measured {d_date}."
    else:
        fluree_line = f"Fluree {d_version} (DBLP-core, measured {d_date}) and {p_version} (Pokec, measured {p_date})."

    subtitle = f"{triples_m}M triples · {d_hw} · a failed query counts as {PENALTY}× the {d_timeout / 1000:g} s timeout"
    charts = {t: dblp_chart([r[:4] for r in d_rows], subtitle, t) for t in THEMES}

    others = ", ".join(f"{r[0]} {fmt_ms(r[1])}" for r in d_rows[1:])
    alt = (f"Bar chart of DBLP-core geometric-mean query time, lower is faster: "
           f"Fluree {fmt_ms(f_ms)} ({f_pass}/{f_total} queries), then {others}")

    commit = bench_commit(bench)
    gh = "https://github.com/fluree/benchmark-db/blob/main"
    block = f"""{START}
<!-- Generated by scripts/readme/sync-bench.py from fluree/benchmark-db@{commit}. Do not edit by hand. -->
<table>
<tr>
<th width="50%" align="left">RDF / SPARQL · <a href="{gh}/{DBLP}/REPORT.md">DBLP-core</a></th>
<th width="50%" align="left">Property graph / Cypher · <a href="{gh}/{POKEC}/REPORT.md">Pokec</a></th>
</tr>
<tr>
<td valign="top"><b>{fmt_ms(f_ms)}</b> geometric mean, <b>{f_pass}/{f_total}</b> queries complete<br>QLever takes <b>{q_ratio:.1f}×</b> as long, Virtuoso <b>{v_ratio:.1f}×</b><br><sub>{triples_m}M triples · {d_hw} · SPARQLoscope, P={PENALTY}</sub></td>
<td valign="top"><b>{fmt_ms(reads['fluree'])}</b> reads · <b>{fmt_ms(writes['fluree'])}</b> durable writes<br><b>{r_ratios[0]:.2f}–{r_ratios[-1]:.2f}×</b> faster reads, <b>{w_ratios[0]:.2f}–{w_ratios[-1]:.2f}×</b> faster writes than FalkorDB, Memgraph and Neo4j<br><sub>{large['nodes'] / 1e6:.1f}M nodes / {large['edges'] / 1e6:.1f}M edges · {p_hw} · {n_queries} queries</sub></td>
</tr>
</table>

<p align="center">
  <picture>
    <source media="(prefers-color-scheme: dark)" srcset="docs/assets/readme/dblp-core-geomean-dark.svg">
    <img src="docs/assets/readme/dblp-core-geomean-light.svg" width="760" alt="{alt}">
  </picture>
</p>

**At Wikidata scale.** On the [full Wikidata dump]({gh}/{WGPB}/REPORT.md) ({w_triples_b:.1f}B distinct triples), Fluree {w_version} completes all {w_res['completed']}/{w_total} WGPB graph-pattern queries with a {fmt_ms(w_res['geo_mean_ms'])} geometric mean. On [Wikidata-truthy]({gh}/{TRUTHY}/REPORT.md) ({t_triples_b:.2f}B triples), Fluree {t_version} answers {t_f[1]}/{t_f[2]} SPARQLoscope queries with a {fmt_ms(t_f[0])} geometric mean; QLever answers {t_q[1]}/{t_q[2]} and takes {t_q[0] / t_f[0]:.1f}× as long.

<sub>{fluree_line} Other engines were measured earlier on the same instance type (Pokec peers: {p_peer_date}); each report lists versions, dates and caveats. The chart is linear up to 500 ms; slower engines are clipped and labeled.</sub>
{END}"""
    return block, charts


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bench-repo", required=True, type=pathlib.Path)
    ap.add_argument("--check", action="store_true", help="exit 1 if anything would change")
    args = ap.parse_args()
    bench = args.bench_repo.resolve()

    readme = README.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(readme):
        print(f"error: {START} … {END} markers not found in README.md", file=sys.stderr)
        return 2
    block, charts = render(bench)
    new_readme = pattern.sub(lambda _: block, readme, count=1)

    changed = []
    if new_readme != readme:
        changed.append("README.md")
    outputs = {ASSETS / f"dblp-core-geomean-{t}.svg": svg for t, svg in charts.items()}
    for path, svg in outputs.items():
        if not path.exists() or path.read_text() != svg:
            changed.append(str(path.relative_to(ROOT)))

    if args.check:
        if changed:
            print("out of date: " + ", ".join(changed))
            return 1
        print("benchmark block is up to date")
        return 0

    README.write_text(new_readme)
    for path, svg in outputs.items():
        path.write_text(svg)
    print("updated: " + (", ".join(changed) if changed else "nothing (already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
