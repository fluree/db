#!/usr/bin/env python3
"""Regenerate the README benchmark block from a fluree/benchmark-db checkout.

The block between <!-- BENCH:START --> and <!-- BENCH:END --> in README.md is
generated by this script; do not edit it by hand. Every number is computed from
benchmark-db's raw per-engine results, not copied from its prose:

  DBLP-core  benchmarks/sparqloscope/reports/dblp-core/engines/<engine>_summary.tsv
             penalized geometric mean (SPARQLoscope P=2): a failed or timed-out
             query counts as 2 x the 180 s timeout.
  Pokec      benchmarks/benchgraph/reports/pokec/summary.tsv
             geometric mean of per-query medians at the large scale, reads and
             writes separately.

Versions and measurement dates come from each report's meta.json. The DBLP-core
chart (assets/dblp-core-geomean.svg) is copied next to the README assets.

Usage:
  python3 scripts/readme/sync-bench.py --bench-repo ../benchmark-db [--check]

--check exits 1 if README.md or the chart would change (for CI).
Standard library only.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
README = ROOT / "README.md"
CHART_DEST = ROOT / "docs/assets/readme/dblp-core-geomean.svg"

START = "<!-- BENCH:START -->"
END = "<!-- BENCH:END -->"

DBLP = "benchmarks/sparqloscope/reports/dblp-core"
POKEC = "benchmarks/benchgraph/reports/pokec"
DBLP_ENGINES = ["fluree", "qlever", "virtuoso"]
POKEC_PEERS = ["falkordb", "memgraph", "neo4j"]
TIMEOUT_MS = 180_000
PENALTY = 2


def geomean(values: list[float]) -> float:
    return math.exp(sum(math.log(v) for v in values) / len(values))


def dblp_engine(bench: pathlib.Path, engine: str) -> tuple[float, int, int]:
    """Return (penalized geomean ms, passed, total) for one engine."""
    path = bench / DBLP / "engines" / f"{engine}_summary.tsv"
    values, passed = [], 0
    with path.open(newline="") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    for row in rows:
        try:
            ms = float(row["median_ms"])
        except (TypeError, ValueError):
            ms = None
        ok = (
            ms is not None
            and row.get("status") == "200"
            and not (row.get("error") or "").strip()
            and ms < TIMEOUT_MS
        )
        if ok:
            passed += 1
            values.append(ms)
        else:
            values.append(PENALTY * TIMEOUT_MS)
    return geomean(values), passed, len(rows)


def pokec_geomeans(bench: pathlib.Path) -> dict[str, dict[str, float]]:
    """Return {kind: {engine: geomean ms}} for the large scale."""
    path = bench / POKEC / "summary.tsv"
    with path.open(newline="") as fh:
        rows = [r for r in csv.DictReader(fh, delimiter="\t") if r["scale"] == "large"]
    out: dict[str, dict[str, float]] = {}
    for kind in ("read", "write"):
        subset = [r for r in rows if r["kind"] == kind]
        out[kind] = {
            eng: geomean([float(r[f"{eng}_ms"]) for r in subset])
            for eng in ["fluree", *POKEC_PEERS]
        }
        out[kind]["_n"] = len(subset)
    return out


def fmt_ms(ms: float) -> str:
    if ms >= 1000:
        return f"{ms / 1000:,.1f} s"
    if ms >= 10:
        return f"{ms:,.1f} ms"
    return f"{ms:.2f} ms"


def bench_commit(bench: pathlib.Path) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(bench), "rev-parse", "--short", "HEAD"], text=True
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def render(bench: pathlib.Path) -> str:
    dmeta = json.loads((bench / DBLP / "meta.json").read_text())
    pmeta = json.loads((bench / POKEC / "meta.json").read_text())

    d = {e: dblp_engine(bench, e) for e in DBLP_ENGINES}
    f_ms, f_pass, f_total = d["fluree"]
    q_ratio = d["qlever"][0] / f_ms
    v_ratio = d["virtuoso"][0] / f_ms
    triples_m = round(dmeta["dataset"]["triples"] / 1e6)
    d_version = dmeta["engines"]["fluree"]["version"]
    d_date = dmeta["engines"]["fluree"].get("measured_at", "unknown date")
    d_hw = dmeta["hardware"]["instance"].replace("AWS ", "")

    p = pokec_geomeans(bench)
    reads, writes = p["read"], p["write"]
    r_ratios = sorted(reads[e] / reads["fluree"] for e in POKEC_PEERS)
    w_ratios = sorted(writes[e] / writes["fluree"] for e in POKEC_PEERS)
    large = pmeta["dataset"]["scales"]["large"]
    p_version = pmeta["engines"]["fluree"]["version"]
    measured = pmeta["methodology"].get("measured", {})
    p_date = measured.get("fluree", "unknown date")
    p_peer_date = measured.get("neo4j", "an earlier date")
    p_hw = pmeta["hardware"]["instance"].replace("AWS ", "")
    n_queries = reads["_n"] + writes["_n"]

    if (d_version, d_date) == (p_version, p_date):
        fluree_line = f"Fluree {d_version}, measured {d_date}."
    else:
        fluree_line = (
            f"Fluree {d_version} (DBLP-core, measured {d_date}) and "
            f"{p_version} (Pokec, measured {p_date})."
        )

    commit = bench_commit(bench)
    alt = (
        f"Bar chart of DBLP-core geometric-mean query time, lower is faster: "
        f"Fluree {fmt_ms(f_ms)} ({f_pass}/{f_total} queries), "
        f"QLever {fmt_ms(d['qlever'][0])} ({q_ratio:.1f}x), "
        f"Virtuoso {fmt_ms(d['virtuoso'][0])} ({v_ratio:.1f}x), "
        f"plus MillenniumDB, Jena, Oxigraph and Blazegraph"
    )

    return f"""{START}
<!-- Generated by scripts/readme/sync-bench.py from fluree/benchmark-db@{commit}. Do not edit by hand. -->
<table>
<tr>
<th width="50%" align="left">RDF / SPARQL · <a href="https://github.com/fluree/benchmark-db/blob/main/{DBLP}/REPORT.md">DBLP-core</a></th>
<th width="50%" align="left">Property graph / Cypher · <a href="https://github.com/fluree/benchmark-db/blob/main/{POKEC}/REPORT.md">Pokec</a></th>
</tr>
<tr>
<td valign="top"><b>{fmt_ms(f_ms)}</b> geometric mean, <b>{f_pass}/{f_total}</b> queries complete<br>QLever takes <b>{q_ratio:.1f}×</b> as long, Virtuoso <b>{v_ratio:.1f}×</b><br><sub>{triples_m}M triples · {d_hw} · SPARQLoscope, P={PENALTY}</sub></td>
<td valign="top"><b>{fmt_ms(reads['fluree'])}</b> reads · <b>{fmt_ms(writes['fluree'])}</b> durable writes<br><b>{r_ratios[0]:.2f}–{r_ratios[-1]:.2f}×</b> faster reads, <b>{w_ratios[0]:.2f}–{w_ratios[-1]:.2f}×</b> faster writes than FalkorDB, Memgraph and Neo4j<br><sub>{large['nodes'] / 1e6:.1f}M nodes / {large['edges'] / 1e6:.1f}M edges · {p_hw} · {n_queries} queries</sub></td>
</tr>
</table>

<p align="center"><img src="docs/assets/readme/dblp-core-geomean.svg" width="680" alt="{alt}"></p>

<sub>{fluree_line} Other engines were measured earlier on the same instance type (Pokec peers: {p_peer_date}); each report lists versions, dates and caveats. Lower latency is better.</sub>
{END}"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bench-repo", required=True, type=pathlib.Path)
    ap.add_argument("--check", action="store_true", help="exit 1 if anything would change")
    args = ap.parse_args()
    bench = args.bench_repo.resolve()

    readme = README.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(readme):
        print(f"error: {START} … {END} markers not found in README.md", file=sys.stderr)
        return 2
    new_readme = pattern.sub(lambda _: render(bench), readme, count=1)

    chart_src = (bench / "assets/dblp-core-geomean.svg").read_bytes()
    chart_old = CHART_DEST.read_bytes() if CHART_DEST.exists() else b""

    changed = []
    if new_readme != readme:
        changed.append("README.md")
    if chart_src != chart_old:
        changed.append(str(CHART_DEST.relative_to(ROOT)))

    if args.check:
        if changed:
            print("out of date: " + ", ".join(changed))
            return 1
        print("benchmark block is up to date")
        return 0

    README.write_text(new_readme)
    CHART_DEST.write_bytes(chart_src)
    print("updated: " + (", ".join(changed) if changed else "nothing (already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
